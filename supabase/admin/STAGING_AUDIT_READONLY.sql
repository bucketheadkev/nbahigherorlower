select 'missing table' as problem, e.name as object
from expected_tables e
where to_regclass('public.' || e.name) is null
union all
select 'missing function', e.name
from expected_functions e
where not exists (
  select 1 from pg_proc p join pg_namespace n on n.oid = p.pronamespace
  where n.nspname = 'public' and p.proname = e.name)
union all
select 'missing trigger', e.tbl || '.' || e.name
from expected_triggers e
where not exists (
  select 1 from pg_trigger t join pg_class c on c.oid = t.tgrelid
  join pg_namespace n on n.oid = c.relnamespace
  where n.nspname = 'public' and c.relname = e.tbl and t.tgname = e.name)
union all
select 'missing policy', e.tbl || '.' || e.name
from expected_policies e
where not exists (
  select 1 from pg_policies p
  where p.schemaname = 'public' and p.tablename = e.tbl and p.policyname = e.name)
union all
-- RLS off is only a problem when anon/authenticated still have table privileges.
-- Service-only tables (REVOKE ALL from clients) are fine without RLS.
select 'RLS disabled', c.relname::text
from pg_class c join pg_namespace n on n.oid = c.relnamespace
where n.nspname = 'public' and c.relkind = 'r' and not c.relrowsecurity
  and (
    has_table_privilege('anon', c.oid, 'select')
    or has_table_privilege('anon', c.oid, 'insert')
    or has_table_privilege('anon', c.oid, 'update')
    or has_table_privilege('anon', c.oid, 'delete')
    or has_table_privilege('authenticated', c.oid, 'select')
    or has_table_privilege('authenticated', c.oid, 'insert')
    or has_table_privilege('authenticated', c.oid, 'update')
    or has_table_privilege('authenticated', c.oid, 'delete')
  )
union all
select 'pg_cron not installed (Circuit auto-settle)', 'extension pg_cron'
where not exists (select 1 from pg_extension where extname = 'pg_cron')
union all
select 'UNSAFE: client can mint coins', 'credit_my_coins'
where to_regprocedure('public.credit_my_coins(bigint,text,text)') is not null
union all
select 'UNSAFE: authenticated can call coin_post', 'coin_post'
where to_regprocedure('public.coin_post(uuid,bigint,text,text,jsonb)') is not null
  and has_function_privilege('authenticated', 'public.coin_post(uuid,bigint,text,text,jsonb)', 'execute')
order by 1, 2;

