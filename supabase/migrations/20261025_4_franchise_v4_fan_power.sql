-- Lock all five and start the 48 hours (server time). Fans, Fan Power and pay are fixed here.
CREATE OR REPLACE FUNCTION public.confirm_franchise_lineup(p_cycle uuid)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
SET row_security = off
AS $$
DECLARE
  v_uid uuid := public.franchise_require_user();
  c public.franchise_cycles%ROWTYPE;
  s public.franchise_settings%ROWTYPE;
  v_price bigint;
  v_total bigint;
  v_fans bigint;
  v_hourly bigint;
BEGIN
  SELECT * INTO c FROM public.franchise_cycles WHERE id = p_cycle AND user_id = v_uid FOR UPDATE;
  IF NOT FOUND THEN
    RAISE EXCEPTION 'cycle_not_found' USING ERRCODE = 'P0002';
  END IF;
  IF c.status <> 'drafting' THEN
    RETURN public.franchise_cycle_json(c);
  END IF;
  IF jsonb_array_length(c.picks) <> 5 THEN
    RAISE EXCEPTION 'lineup_incomplete' USING ERRCODE = 'P0001';
  END IF;
  SELECT price_paid INTO v_price FROM public.franchise_ownership WHERE user_id = v_uid AND team_id = c.team_id;
  IF v_price IS NULL THEN
    RAISE EXCEPTION 'not_owned' USING ERRCODE = '42501';
  END IF;

  SELECT * INTO s FROM public.franchise_settings WHERE id;
  SELECT sum(public.classic_seat_value(p ->> 'player_id', p ->> 'slot'))::bigint, coalesce(sum(pool.fans), 0)::bigint
  INTO v_total, v_fans
  FROM jsonb_array_elements(c.picks) p
  LEFT JOIN public.franchise_player_pool pool ON pool.player_id = p ->> 'player_id';
  v_hourly := public.franchise_hourly(v_price, v_fans);

  UPDATE public.franchise_cycles
  SET status = 'earning',
      lineup_value = v_total,
      fans = v_fans,
      fan_power_milli = public.franchise_fan_power_milli(v_fans),
      price_basis = v_price,
      payout_bps = NULL,
      cycle_total = v_hourly * s.cycle_hours,
      hourly_rate = v_hourly,
      hours_total = s.cycle_hours,
      completion_bonus = 0,
      payout = v_hourly * s.cycle_hours,
      hours_paid = 0,
      bonus_paid = false,
      locked_at = now(),
      ends_at = now() + make_interval(hours => s.cycle_hours)
  WHERE id = c.id
  RETURNING * INTO c;
  RETURN public.franchise_cycle_json(c);
END;
$$;

REVOKE ALL ON FUNCTION public.confirm_franchise_lineup(uuid) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.confirm_franchise_lineup(uuid) TO authenticated;

-- ---------------------------------------------------------------------------
-- Rosters earning right now: pay what they've earned, then move the rest to v4 pay
-- ---------------------------------------------------------------------------

DO $$
DECLARE
  c record;
  v_fans bigint;
  v_hourly bigint;
  v_paid bigint;
BEGIN
  FOR c IN
    SELECT * FROM public.franchise_cycles
    WHERE status = 'earning' AND now() < ends_at AND fans IS NOT NULL AND coalesce(completion_bonus, 0) = 0
  LOOP
    PERFORM public.franchise_settle(c.id);
    SELECT coalesce(sum(pool.fans), 0)::bigint INTO v_fans
    FROM jsonb_array_elements(c.picks) p
    LEFT JOIN public.franchise_player_pool pool ON pool.player_id = p ->> 'player_id';
    v_hourly := public.franchise_hourly(c.price_basis, v_fans);
    SELECT coalesce(sum(amount), 0) INTO v_paid
    FROM public.bank_ledger
    WHERE user_id = c.user_id AND kind = 'franchise_income' AND source_ref LIKE c.id::text || ':%';
    UPDATE public.franchise_cycles
    SET fans = v_fans,
        fan_power_milli = public.franchise_fan_power_milli(v_fans),
        hourly_rate = v_hourly,
        cycle_total = v_paid + (hours_total - hours_paid)::bigint * v_hourly,
        payout = v_paid + (hours_total - hours_paid)::bigint * v_hourly,
        picks = (
          SELECT jsonb_agg(p || jsonb_build_object('fans', coalesce(pool.fans, 0)))
          FROM jsonb_array_elements(c.picks) p
          LEFT JOIN public.franchise_player_pool pool ON pool.player_id = p ->> 'player_id'
        )
    WHERE id = c.id AND status = 'earning';
  END LOOP;
