    'id', c.id,
    'team_id', c.team_id,
    'status', CASE
                WHEN c.status = 'earning' AND now() >= c.ends_at THEN 'complete'
                ELSE c.status
              END,
    'picks', c.picks,
    'spin', CASE WHEN c.spin_team IS NULL THEN NULL
                 ELSE jsonb_build_object('team_id', c.spin_team, 'era', c.spin_era) END,
    'spins', c.spins,
    'lineup_value', c.lineup_value,
    'fans', c.fans,
