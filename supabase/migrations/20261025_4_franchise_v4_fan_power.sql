-- Franchise v4: player fans + Fan Power pay (2026-10-25).
-- Paste after 20261025_2_franchise_v3_fans.sql. Source of truth: lib/tradeup/ownership/config.ts
-- and lib/tradeup/ownership/fans.ts (the generated block below comes from
-- scripts/generate-franchise-seed.ts).
--
--   * Every player has a fan count (the same person in every era): stars draw hundreds of
--     millions; Michael Jordan, LeBron James and Wilt Chamberlain lead with 500,000,000+.
--   * Fan Power = the five players' total fans ÷ fans_per_power (1,000,000,000), capped at
--     max_power_milli (2.000), kept in thousandths.
--   * Each hour of the 48 pays: price paid × hourly_ppm (750 = 0.075%) × Fan Power.
--     A $200,000,000 franchise tops out at $300,000 / hour ($14,400,000 per 48 hours); a
--     $20,000,000 franchise at $30,000 / hour. Cheaper franchises always earn less for the
--     same roster.
--   * Rosters already earning under v3 keep everything earned so far (paid now at their old
--     rate); their remaining hours pay the v4 rate.
--
-- In-game Cash only. Apply manually in the Supabase SQL Editor. Safe to re-run.

ALTER TABLE public.franchise_settings ADD COLUMN IF NOT EXISTS fans_per_power bigint NOT NULL DEFAULT 1000000000;
ALTER TABLE public.franchise_settings ADD COLUMN IF NOT EXISTS max_power_milli integer NOT NULL DEFAULT 2000;
ALTER TABLE public.franchise_settings ADD COLUMN IF NOT EXISTS hourly_ppm integer NOT NULL DEFAULT 750;
ALTER TABLE public.franchise_settings DROP CONSTRAINT IF EXISTS franchise_settings_v4_check;
ALTER TABLE public.franchise_settings ADD CONSTRAINT franchise_settings_v4_check
  CHECK (fans_per_power >= 1000 AND max_power_milli > 0 AND hourly_ppm > 0);

ALTER TABLE public.franchise_player_pool ADD COLUMN IF NOT EXISTS fans bigint NOT NULL DEFAULT 0;
ALTER TABLE public.franchise_cycles ADD COLUMN IF NOT EXISTS fan_power_milli integer;

