RETURNS integer
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = public
AS $$
  SELECT least(s.max_power_milli::bigint, greatest(coalesce(p_fans, 0), 0) / (s.fans_per_power / 1000))::integer
  FROM public.franchise_settings s
  WHERE s.id;
