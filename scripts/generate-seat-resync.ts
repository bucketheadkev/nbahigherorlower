/**
 * Writes a migration that brings the live seat-price catalog in line with the app, without
 * truncating, then re-prices recent runs that were verified with the old catalog.
 * Run: npx tsx --tsconfig tsconfig.json scripts/generate-seat-resync.ts
 */
import { writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { getDollarValueForSlot } from '../lib/tradeup/billionDollar';
import {
  DECADE_ERAS,
  decadePlayerToTradePlayer,
  getDecadeRoster,
  teamsForEra,
} from '../lib/tradeup/decadeRosters';
import { LINEUP_POSITIONS } from '../lib/tradeup/startingLineup';

const OUT = join(process.cwd(), 'supabase/migrations/20261019_2_seat_values_resync.sql');

const rows = new Map<string, string>();
for (const era of DECADE_ERAS) {
  for (const team of teamsForEra(era)) {
    for (const row of getDecadeRoster(team.id, era)) {
      const player = decadePlayerToTradePlayer(row, team.id, era);
      if (rows.has(player.id)) continue;
      const values = LINEUP_POSITIONS.map((slot) => getDollarValueForSlot(player, slot));
      rows.set(
        player.id,
        `('${player.id.replace(/'/g, "''")}', '${player.primaryPosition}', ${values.join(', ')})`,
      );
    }
  }
}

const sorted = [...rows.entries()].sort(([a], [b]) => a.localeCompare(b)).map(([, v]) => v);
const BATCH = 250;
const inserts: string[] = [];
for (let i = 0; i < sorted.length; i += BATCH) {
  inserts.push(
    [
      'INSERT INTO public.classic_player_seat_values (',
      '  player_id, primary_position, value_pg, value_sg, value_sf, value_pf, value_c',
      ') VALUES',
      sorted.slice(i, i + BATCH).map((r) => `  ${r}`).join(',\n'),
      'ON CONFLICT (player_id) DO UPDATE',
      '  SET primary_position = EXCLUDED.primary_position,',
      '      value_pg = EXCLUDED.value_pg,',
      '      value_sg = EXCLUDED.value_sg,',
      '      value_sf = EXCLUDED.value_sf,',
      '      value_pf = EXCLUDED.value_pf,',
      '      value_c = EXCLUDED.value_c;',
      '',
    ].join('\n'),
  );
}

const sql = `-- Seat-price resync (2026-10-19). Auto-generated by scripts/generate-seat-resync.ts — do not edit by hand.
--
-- The live catalog was an older generation (≈6% off-position discount and older star prices), so the
-- server verified Classic runs several million below the value the app showed — e.g. a $1,007,000,000
-- run verified at $998,000,000, which blocked its Surplus and Bet on Yourself payouts.
-- This upserts every player's seat prices from the app's own pricing (${sorted.length} players), then:
--   * re-prices runs since the Bank launch that have no Surplus decision yet (their Surplus becomes
--     claimable from the home screen when the new value is over $1B),
--   * raises personal bests where the re-priced value is higher,
--   * updates run values in Cash Leagues that are still open.
-- Settled Bet on Yourself slips and paid Surplus decisions are not changed.
--
-- In-game Cash only. Apply manually in the Supabase SQL Editor. Safe to re-run.

${inserts.join('\n')}
-- Re-price recent runs with the corrected catalog.
WITH priced AS (
  SELECT r.id,
         sum(public.classic_seat_value(s ->> 'player_id', s ->> 'slot'))::bigint AS value,
         count(public.classic_seat_value(s ->> 'player_id', s ->> 'slot')) AS seats
  FROM public.user_leaderboard_runs r
  CROSS JOIN LATERAL jsonb_array_elements(r.lineup) s
  WHERE r.achieved_at >= public.surplus_launch_at()
    AND NOT EXISTS (SELECT 1 FROM public.surplus_decisions d WHERE d.run_id = r.id)
  GROUP BY r.id
)
UPDATE public.user_leaderboard_runs r
SET verified_value = p.value
FROM priced p
WHERE r.id = p.id AND p.seats = 5 AND r.verified_value <> p.value;

-- Personal bests only move up.
UPDATE public.user_leaderboard_pb pb
SET verified_best = best.verified_value,
    best_run_id = best.id,
    achieved_at = best.achieved_at,
    updated_at = now()
FROM (
  SELECT DISTINCT ON (user_id) user_id, id, verified_value, achieved_at
  FROM public.user_leaderboard_runs
  ORDER BY user_id, verified_value DESC, achieved_at ASC
) best
WHERE pb.user_id = best.user_id AND best.verified_value > pb.verified_best;

-- Open Cash Leagues use the corrected run values.
UPDATE public.circuit_entries e
SET run_value = r.verified_value
FROM public.user_leaderboard_runs r, public.circuit_competitions c
WHERE e.run_id = r.id
  AND c.id = e.competition_id
  AND c.status = 'open'
  AND e.run_value IS DISTINCT FROM r.verified_value;
`;

writeFileSync(OUT, sql, 'utf8');
console.log(`wrote ${OUT} (${sorted.length} players, ${(sql.length / 1024).toFixed(0)} KB)`);
