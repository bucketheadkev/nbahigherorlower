/**
 * Writes a migration that re-prices the live seat catalog at full value for every position
 * (no primary/alternate difference), straight from the app's own pricing.
 * Run: npx tsx --tsconfig tsconfig.json scripts/generate-seat-full-value.ts
 */
import { writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { getDollarValueForSlot } from '../lib/tradeup/billionDollar';
import {
  DECADE_ERAS,
  decadePlayerToTradePlayer,
  getDecadeRoster,
  teamsForEra,
} from '../lib/tradeup/decadeRosters';
import { LINEUP_POSITIONS } from '../lib/tradeup/startingLineup';

const OUT = join(process.cwd(), 'supabase/migrations/20261108_2_seat_values_full_value.sql');

const rows = new Map<string, string>();
for (const era of DECADE_ERAS) {
  for (const team of teamsForEra(era)) {
    for (const row of getDecadeRoster(team.id, era)) {
      const player = decadePlayerToTradePlayer(row, team.id, era);
      if (rows.has(player.id)) continue;
      const values = LINEUP_POSITIONS.map((slot) => getDollarValueForSlot(player, slot));
      if (new Set(values).size !== 1) throw new Error(`${player.id} has different seat prices`);
      rows.set(
        player.id,
        `('${player.id.replace(/'/g, "''")}', '${player.primaryPosition}', ${values.join(', ')})`,
      );
    }
  }
}

const sorted = [...rows.entries()].sort(([a], [b]) => a.localeCompare(b)).map(([, v]) => v);
const BATCH = 250;
const inserts: string[] = [];
for (let i = 0; i < sorted.length; i += BATCH) {
  inserts.push(
    [
      'INSERT INTO public.classic_player_seat_values (',
      '  player_id, primary_position, value_pg, value_sg, value_sf, value_pf, value_c',
      ') VALUES',
      sorted.slice(i, i + BATCH).map((r) => `  ${r}`).join(',\n'),
      'ON CONFLICT (player_id) DO UPDATE',
      '  SET primary_position = EXCLUDED.primary_position,',
      '      value_pg = EXCLUDED.value_pg,',
      '      value_sg = EXCLUDED.value_sg,',
      '      value_sf = EXCLUDED.value_sf,',
      '      value_pf = EXCLUDED.value_pf,',
      '      value_c = EXCLUDED.value_c;',
      '',
    ].join('\n'),
  );
}

const sql = `-- Full value at every position (2026-11-08). Auto-generated by scripts/generate-seat-full-value.ts — do not edit by hand.
--
-- The app no longer takes 3% off a player seated outside his primary position: every player is worth
-- his full fixed value at every position he is eligible for. The server verifies Classic runs (and so
-- the leaderboard, Run Bonuses, Bank Surplus, Bet on Yourself and Cash Leagues) from this catalog, so it
-- must match. This upserts all ${sorted.length} players' seat prices; nothing else changes. Runs already
-- verified keep their values.
--
-- In-game Cash only. Apply manually in the Supabase SQL Editor. Safe to re-run.

${inserts.join('\n')}`;

writeFileSync(OUT, sql, 'utf8');
console.log(`wrote ${OUT} (${sorted.length} players, ${(sql.length / 1024).toFixed(0)} KB)`);
