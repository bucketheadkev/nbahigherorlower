/**
 * Writes the Franchise seed from lib/tradeup/ownership/config.ts, lib/tradeup/ownership/fans.ts and
 * the Classic player pool:
 *   - supabase/migrations/20261024_4_franchise_seed.sql — player pool (era, team, eligible seats)
 *   - the GENERATED FRANCHISE DATA block of 20261025_4_franchise_v4_fan_power.sql — settings,
 *     tiers, prices and every player's fans
 * Run after changing the config: npx tsx --tsconfig tsconfig.json scripts/generate-franchise-seed.ts
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { getEligiblePositions } from '../lib/tradeup/alternatePositions';
import {
  DECADE_ERAS,
  decadePlayerToTradePlayer,
  getDecadeRoster,
  teamsForEra,
} from '../lib/tradeup/decadeRosters';
import {
  CHAMPIONSHIPS,
  compareFranchises,
  CYCLE_HOURS,
  EARNINGS,
  FRANCHISE_TIER,
  franchisePrice,
  franchiseTier,
  RESALE,
} from '../lib/tradeup/ownership/config';
import { fanTable, LEGEND_FANS } from '../lib/tradeup/ownership/fans';
import { TEAMS } from '../lib/tradeup/teams';

const POOL_OUT = join(process.cwd(), 'supabase/migrations/20261024_4_franchise_seed.sql');
const V4 = join(process.cwd(), 'supabase/migrations/20261025_4_franchise_v4_fan_power.sql');
const BEGIN = '-- BEGIN GENERATED FRANCHISE DATA (scripts/generate-franchise-seed.ts — do not edit by hand)';
const END = '-- END GENERATED FRANCHISE DATA';
const esc = (s: string) => s.replace(/'/g, "''");

const missing = TEAMS.filter((t) => CHAMPIONSHIPS[t.id] == null || FRANCHISE_TIER[t.id] == null);
if (missing.length > 0 || TEAMS.length !== 30) {
  throw new Error(`Franchise tables incomplete: ${missing.map((t) => t.id).join(', ')}`);
}

const catalog = TEAMS.map((t) => ({ teamId: t.id, name: t.fullName, championships: CHAMPIONSHIPS[t.id]! }))
  .sort(compareFranchises)
  .map(
    (t, i) =>
      `  ('${t.teamId}', '${esc(t.name)}', ${t.championships}, '${franchiseTier(t.teamId)}', ${franchisePrice(t.teamId)}, ${i + 1})`,
  );

const fans = fanTable();
for (const slug of Object.keys(LEGEND_FANS)) {
  if (!fans.has(slug)) throw new Error(`Legend ${slug} is not in the player pool`);
}
const fanRows = [...fans.entries()].sort(([a], [b]) => a.localeCompare(b)).map(([slug, n]) => `  ('${esc(slug)}', ${n})`);

const block = `${BEGIN}
INSERT INTO public.franchise_settings (id, cycle_hours, resale_bps, fans_per_power, max_power_milli, hourly_ppm)
VALUES (true, ${CYCLE_HOURS}, ${RESALE.refundBps}, ${EARNINGS.fansPerPower}, ${EARNINGS.maxPowerMilli}, ${EARNINGS.hourlyPpm})
ON CONFLICT (id) DO UPDATE
  SET cycle_hours = EXCLUDED.cycle_hours,
      resale_bps = EXCLUDED.resale_bps,
      fans_per_power = EXCLUDED.fans_per_power,
      max_power_milli = EXCLUDED.max_power_milli,
      hourly_ppm = EXCLUDED.hourly_ppm;

-- team, name, championships (verified Oct 2026), tier, price, sort
INSERT INTO public.franchise_catalog (team_id, name, championships, tier, price, sort) VALUES
${catalog.join(',\n')}
ON CONFLICT (team_id) DO UPDATE
  SET name = EXCLUDED.name,
      championships = EXCLUDED.championships,
      tier = EXCLUDED.tier,
      price = EXCLUDED.price,
      sort = EXCLUDED.sort;

-- Fans per player (${fanRows.length} players; the same person in every era and team).
UPDATE public.franchise_player_pool pool
SET fans = f.fans
FROM (VALUES
${fanRows.join(',\n')}
) AS f (slug, fans)
WHERE public.franchise_player_slug(pool.player_id) = f.slug;
${END}`;

const v4 = readFileSync(V4, 'utf8');
const start = v4.indexOf(BEGIN);
const stop = v4.indexOf(END);
if (start < 0 || stop < start) throw new Error(`Data markers missing in ${V4}`);
writeFileSync(V4, v4.slice(0, start) + block + v4.slice(stop + END.length), 'utf8');

const pool = new Map<string, string>();
for (const era of DECADE_ERAS) {
  for (const team of teamsForEra(era)) {
    for (const row of getDecadeRoster(team.id, era)) {
      const player = decadePlayerToTradePlayer(row, team.id, era);
      if (pool.has(player.id)) continue;
      const eligible = getEligiblePositions(player).map((p) => `'${p}'`).join(', ');
      pool.set(player.id, `  ('${esc(player.id)}', '${team.id}', '${era}', ARRAY[${eligible}]::text[])`);
    }
  }
}
const poolRows = [...pool.entries()].sort(([a], [b]) => a.localeCompare(b)).map(([, v]) => v);

const BATCH = 400;
const poolInserts: string[] = [];
for (let i = 0; i < poolRows.length; i += BATCH) {
  poolInserts.push(
    `INSERT INTO public.franchise_player_pool (player_id, team_id, era, eligible) VALUES\n${poolRows
      .slice(i, i + BATCH)
      .join(',\n')}\nON CONFLICT (player_id) DO UPDATE\n  SET team_id = EXCLUDED.team_id, era = EXCLUDED.era, eligible = EXCLUDED.eligible;\n`,
  );
}

const sql = `-- Franchise player pool. Auto-generated by scripts/generate-franchise-seed.ts — do not edit by hand.
-- Requires 20261024_1_franchises.sql and 20261024_3_franchise_v2_ranks.sql. Safe to re-run (upserts).
-- Settings, tiers, prices and fans live in 20261025_4_franchise_v4_fan_power.sql.

-- Classic player pool: ${poolRows.length} players (era + team + eligible seats).
${poolInserts.join('\n')}`;

writeFileSync(POOL_OUT, sql, 'utf8');
console.log(`wrote ${POOL_OUT} (${poolRows.length} players) and the data block of ${V4} (${catalog.length} franchises, ${fanRows.length} fan rows)`);
