/**
 * Mac-side "iOS" workflow: safely pull the current branch, install dependencies only when they
 * changed, build + sync Capacitor, re-resolve Swift packages, verify an Xcode build, then open
 * Xcode for physical iPhone testing.
 *
 *     npm run ios
 *
 * Safety: never stashes, resets, discards, merges another branch, force-pushes or deploys.
 * It stops and explains instead when the tree has local edits or the branch has diverged.
 * Docs: docs/WINDOWS_MAC_WORKFLOW.md
 */

import { spawnSync } from 'node:child_process';
import { existsSync, readdirSync, readFileSync, rmSync } from 'node:fs';
import os from 'node:os';
import path from 'node:path';

const root = process.cwd();
const iosAppDir = path.join(root, 'ios', 'App');
const capSpmDir = path.join(iosAppDir, 'CapApp-SPM');
const capSpmPackage = path.join(capSpmDir, 'Package.swift');
/** Regenerated by `cap sync` / SPM resolve — must not block Mac pulls. */
const CAP_SYNC_ARTIFACTS = [
  'ios/App/CapApp-SPM/Package.swift',
  'ios/App/App.xcodeproj/project.xcworkspace/xcshareddata/swiftpm/Package.resolved',
];
const PROD_REF = 'rqogjyjfatnyuoorvyix';
const STAGING_REF = 'wxifsgypdyrruxybcrcw';

const say = (msg) => console.log(`\n[ios] ${msg}`);
const stop = (msg) => {
  console.error(`\n[ios] STOPPED: ${msg}`);
  process.exit(1);
};

function git(args, { allowFail = false } = {}) {
  const r = spawnSync('git', args, { cwd: root, encoding: 'utf8' });
  if (r.status !== 0 && !allowFail) stop(`git ${args.join(' ')} failed:\n${(r.stderr || r.stdout).trim()}`);
  return { ok: r.status === 0, out: (r.stdout || '').trim(), err: (r.stderr || '').trim() };
}

function run(cmd, args, opts = {}) {
  const r = spawnSync(cmd, args, { cwd: opts.cwd || root, stdio: 'inherit', env: opts.env });
  return r.status ?? 1;
}

function capture(cmd, args, opts = {}) {
  const r = spawnSync(cmd, args, {
    cwd: opts.cwd || root,
    encoding: 'utf8',
    env: opts.env,
  });
  return {
    status: r.status ?? 1,
    out: `${r.stdout || ''}${r.stderr || ''}`.trim(),
  };
}

/** Paths of modified tracked files (no untracked), relative to repo root. */
function dirtyTrackedPaths() {
  const out = git(['status', '--porcelain', '--untracked-files=no']).out;
  if (!out) return [];
  return out
    .split('\n')
    .map((line) => line.trimEnd())
    .filter(Boolean)
    .map((line) => line.slice(3).replace(/ -> /, ' ').split(' ').pop());
}

function isOnlyCapSyncArtifacts(paths) {
  return paths.length > 0 && paths.every((p) => CAP_SYNC_ARTIFACTS.includes(p));
}

/**
 * Cap sync rewrites Package.swift / Package.resolved every build. Restoring the
 * committed copies after a successful SPM verify keeps the Mac tree clean so the
 * next `npm run ios` can fast-forward without false "uncommitted changes" stops.
 */
function restoreCapSyncArtifacts(reason) {
  const present = CAP_SYNC_ARTIFACTS.filter((p) => existsSync(path.join(root, p)));
  if (!present.length) return;
  const r = git(['checkout', '--', ...present], { allowFail: true });
  if (!r.ok) {
    stop(`could not restore Capacitor sync artifacts (${reason}):\n${r.err || r.out}`);
  }
  say(`restored Capacitor sync artifacts (${reason}): ${present.join(', ')}`);
}

/**
 * CapApp-SPM depends on local path packages under node_modules/@capacitor/*.
 * After npm ci those paths are new trees; stale Xcode DerivedData then reports
 * "Missing package product CapacitorApp / Browser / Filesystem / Haptics / Share".
 */
function assertCapacitorSpmReady() {
  if (!existsSync(capSpmPackage)) {
    stop(`missing ${path.relative(root, capSpmPackage)}. Run cap sync ios first.`);
  }

  const pkg = readFileSync(capSpmPackage, 'utf8');
  const pathDeps = [...pkg.matchAll(/\.package\(\s*name:\s*"([^"]+)"\s*,\s*path:\s*"([^"]+)"\s*\)/g)].map(
    ([, name, rel]) => ({ name, rel }),
  );
  if (pathDeps.length === 0) {
    stop(
      'CapApp-SPM/Package.swift has no local Capacitor plugin packages.\n' +
        'Capacitor sync should have written them. Check npm run build:ios / npx cap sync ios output.',
    );
  }

  const missing = [];
  for (const { name, rel } of pathDeps) {
    const abs = path.resolve(capSpmDir, rel);
    const pluginPackage = path.join(abs, 'Package.swift');
    if (!existsSync(pluginPackage)) {
      missing.push(`${name} → ${path.relative(root, pluginPackage)}`);
      continue;
    }
    const pluginPkg = readFileSync(pluginPackage, 'utf8');
    // Official Capacitor plugins use the same name for package + library product.
    if (!new RegExp(`name:\\s*"${name}"`).test(pluginPkg)) {
      missing.push(`${name} (Package.swift does not declare product/package "${name}")`);
    }
  }

  if (missing.length) {
    stop(
      'Capacitor Swift packages are incomplete after install/sync:\n' +
        missing.map((m) => `  - ${m}`).join('\n') +
        '\n\nRe-run npm ci, then npm run build:ios. Do not remove plugins to bypass this.',
    );
  }

  say(`Capacitor SPM plugins ready: ${pathDeps.map((d) => d.name).join(', ')}`);
}

function clearAppDerivedData() {
  const derivedRoot = path.join(os.homedir(), 'Library', 'Developer', 'Xcode', 'DerivedData');
  if (!existsSync(derivedRoot)) return 0;
  let removed = 0;
  for (const name of readdirSync(derivedRoot)) {
    if (!name.startsWith('App-')) continue;
    const full = path.join(derivedRoot, name);
    try {
      rmSync(full, { recursive: true, force: true });
      removed += 1;
    } catch (err) {
      stop(
        `could not clear stale Xcode DerivedData at ${full}.\n` +
          `Quit Xcode and type "iOS" again.\n${err instanceof Error ? err.message : String(err)}`,
      );
    }
  }
  return removed;
}

function resolveAndVerifyXcodeBuild({ forceCleanDerivedData }) {
  assertCapacitorSpmReady();

  if (forceCleanDerivedData) {
    say('clearing stale Xcode DerivedData (Capacitor path packages were reinstalled) ...');
    const n = clearAppDerivedData();
    say(n ? `removed ${n} DerivedData folder(s).` : 'no App-* DerivedData to remove.');
  }

  say('resolving Swift Package Manager dependencies ...');
  const resolve = capture(
    'xcodebuild',
    [
      '-project',
      'App.xcodeproj',
      '-scheme',
      'App',
      '-destination',
      'generic/platform=iOS',
      '-resolvePackageDependencies',
    ],
    { cwd: iosAppDir },
  );
  if (resolve.status !== 0) {
    stop(`xcodebuild -resolvePackageDependencies failed:\n${resolve.out.slice(-4000)}`);
  }
  for (const name of ['CapacitorApp', 'CapacitorBrowser', 'CapacitorFilesystem', 'CapacitorHaptics', 'CapacitorShare']) {
    if (!resolve.out.includes(name)) {
      stop(
        `Swift package graph is missing ${name} after resolve.\n` +
          'CapApp-SPM path packages did not load. Check node_modules/@capacitor/* and CapApp-SPM/Package.swift.',
      );
    }
  }
  say('Swift packages resolved (CapacitorApp, Browser, Filesystem, Haptics, Share).');

  say('verifying Xcode build (CODE_SIGNING_ALLOWED=NO) ...');
  const build = capture(
    'xcodebuild',
    [
      '-project',
      'App.xcodeproj',
      '-scheme',
      'App',
      '-destination',
      'generic/platform=iOS',
      '-configuration',
      'Debug',
      'build',
      'CODE_SIGNING_ALLOWED=NO',
    ],
    { cwd: iosAppDir },
  );
  if (build.status !== 0 || !build.out.includes('BUILD SUCCEEDED')) {
    stop(
      'xcodebuild did not report BUILD SUCCEEDED. Xcode was not opened.\n' +
        build.out.slice(-5000),
    );
  }
  say('Xcode BUILD SUCCEEDED.');
}

if (process.platform !== 'darwin') {
  stop('this builds the native iOS app and only runs on the Mac. On Windows: commit + push, then type "iOS" in Cursor on the MacBook.');
}

// 1. Where are we?
const branch = git(['rev-parse', '--abbrev-ref', 'HEAD']).out;
if (branch === 'HEAD') stop('detached HEAD. Check out the feature branch first (git switch <branch>).');
say(`branch: ${branch}`);

// 2. Local edits block the pull — never discard real work.
// Cap sync artifacts are regenerated every build; restore them so they never block.
let dirtyPaths = dirtyTrackedPaths();
if (isOnlyCapSyncArtifacts(dirtyPaths)) {
  say('only Capacitor sync artifacts are dirty — restoring committed copies before pull ...');
  restoreCapSyncArtifacts('pre-pull');
  dirtyPaths = dirtyTrackedPaths();
}
if (dirtyPaths.length && dirtyPaths.every((p) => p.endsWith('tsconfig.tsbuildinfo'))) {
  stop(
    'the only local change is tsconfig.tsbuildinfo (TypeScript build cache, now untracked upstream).\n' +
      'Nothing was pulled. It is safe to restore with:  git checkout -- tsconfig.tsbuildinfo\n' +
      'Confirm in Cursor (or run it yourself), then type "iOS" again.',
  );
}
if (dirtyPaths.length) {
  stop(
    `the Mac has uncommitted changes to tracked files:\n${dirtyPaths.map((p) => ` ${p}`).join('\n')}\n\n` +
      'Nothing was pulled or changed. Decide what to do with them (commit, or ask Cursor to help), then type "iOS" again.',
  );
}

// 3. Fast-forward only.
say(`fetching origin/${branch} ...`);
git(['fetch', 'origin', branch]);
const oldHead = git(['rev-parse', 'HEAD']).out;
const upstream = `origin/${branch}`;
const [behind, ahead] = git(['rev-list', '--left-right', '--count', `${upstream}...HEAD`])
  .out.split(/\s+/)
  .map(Number);

if (behind > 0 && ahead > 0) {
  stop(
    `this Mac has ${ahead} local commit(s) and origin has ${behind} new commit(s) — the branch has diverged.\n` +
      'Nothing was changed. Resolve it deliberately (ask Cursor to help), then type "iOS" again.',
  );
}
if (behind > 0) {
  say(`pulling ${behind} new commit(s) (fast-forward only) ...`);
  git(['merge', '--ff-only', upstream]);
} else {
  say('already up to date with origin.');
}
if (ahead > 0) say(`note: this Mac has ${ahead} commit(s) not pushed to origin.`);
const newHead = git(['rev-parse', 'HEAD']).out;

// 4. Dependencies only when the lockfile changed (or were never installed).
const depsChanged =
  oldHead !== newHead && git(['diff', '--name-only', oldHead, newHead, '--', 'package.json', 'package-lock.json']).out !== '';
const nodeModulesMissing = !existsSync(path.join(root, 'node_modules'));
let ranNpmCi = false;
if (nodeModulesMissing || depsChanged) {
  say(depsChanged ? 'package.json / package-lock.json changed — running npm ci ...' : 'node_modules missing — running npm ci ...');
  if (run('npm', ['ci', '--no-audit', '--no-fund']) !== 0) stop('npm ci failed (see output above).');
  ranNpmCi = true;
} else {
  say('dependencies unchanged — skipping install.');
}

// 5. Which backend will this build talk to? (host only, never keys)
const envFile = path.join(root, '.env.local');
let ref = '';
if (existsSync(envFile)) {
  const m = readFileSync(envFile, 'utf8').match(/^\s*NEXT_PUBLIC_SUPABASE_URL\s*=\s*https?:\/\/([a-z0-9]+)\.supabase\.co/m);
  ref = m ? m[1] : '';
}
if (!ref) {
  say('WARNING: .env.local has no NEXT_PUBLIC_SUPABASE_URL — accounts / leaderboards will not work in this build.');
} else {
  const label = ref === PROD_REF ? 'PRODUCTION' : ref === STAGING_REF ? 'staging' : 'unknown project';
  say(`backend in this build: ${label} (${ref}.supabase.co)`);
}

// 6. Build + sync Capacitor web assets into ios/
say('building and syncing Capacitor (npm run build:ios) ...');
if (run('npm', ['run', 'build:ios']) !== 0) stop('npm run build:ios failed (see output above). Xcode was not opened.');

// 7. Re-resolve SPM + verify native compile before opening Xcode.
// Path packages under node_modules break stale DerivedData after npm ci.
resolveAndVerifyXcodeBuild({ forceCleanDerivedData: ranNpmCi });

// Keep the working tree clean for the next pull (cap sync rewrote artifacts above).
const postBuildDirty = dirtyTrackedPaths();
if (isOnlyCapSyncArtifacts(postBuildDirty)) {
  restoreCapSyncArtifacts('post-verify');
} else if (postBuildDirty.length) {
  say(
    `note: tracked files still dirty after verify (not auto-restored):\n${postBuildDirty.map((p) => `  ${p}`).join('\n')}`,
  );
}

say('opening Xcode ...');
if (run('npx', ['cap', 'open', 'ios']) !== 0) stop('could not open Xcode (npx cap open ios).');

const head = git(['log', '-1', '--format=%h %s']).out;
say(`ready: ${branch} @ ${head}`);
say('In Xcode: pick your iPhone as the run destination and press Run (Cmd+R).');
